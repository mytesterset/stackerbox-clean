import type { HtmlMeta, LayerData } from '$lib/types';
import { CANVAS_MIN, CANVAS_MAX } from '$lib/types';
import { safeNumber, MAX_DIMENSION } from '$lib/utils/validation';
import { ARWEAVE_GATEWAYS } from './turbo';

export interface ArweaveLayerRef {
	layer: LayerData;
	txId: string;
	contentHash?: string;
}

interface ArweaveHtmlInput {
	name: string;
	settings: { width: number; height: number };
	layers: ArweaveLayerRef[];
	gateways?: string[];
	htmlMeta?: HtmlMeta;
}

const CORE_GATEWAYS = ['https://arweave.net', 'https://permagate.io'];

function layerStyle(layer: LayerData): string {
	const x = safeNumber(layer.x, -MAX_DIMENSION, MAX_DIMENSION);
	const y = safeNumber(layer.y, -MAX_DIMENSION, MAX_DIMENSION);
	const w = safeNumber(layer.width, CANVAS_MIN, MAX_DIMENSION);
	const h = safeNumber(layer.height, CANVAS_MIN, MAX_DIMENSION);
	const opacity = safeNumber(layer.opacity, 0, 100) / 100;
	const z = safeNumber(layer.order, 0, 10000);
	return `position: absolute; left: ${x}px; top: ${y}px; width: ${w}px; height: ${h}px; opacity: ${opacity}; z-index: ${z}`;
}

export function generateArweaveIndexHtml({ name, settings, layers, gateways, htmlMeta }: ArweaveHtmlInput): string {
	const gatewayHosts = gateways ?? [...ARWEAVE_GATEWAYS];
	const gatewaysJson = JSON.stringify(gatewayHosts.map((g) => `https://${g}`));
	const coreGatewaysJson = JSON.stringify(CORE_GATEWAYS);

	let layerElements = '';

	for (const { layer, txId, contentHash } of layers) {
		const style = layerStyle(layer);

		if (layer.type === 'html') {
			layerElements += `<iframe data-tx="${escapeHtml(txId)}" data-hash="${escapeHtml(contentHash ?? '')}" data-kind="iframe" style="${style}; border: none;" sandbox=""></iframe>\n`;
		} else {
			layerElements += `<img data-tx="${escapeHtml(txId)}" data-kind="img" alt="${escapeHtml(layer.name)}" style="${style}" />\n`;
		}
	}

	const title = escapeHtml(name || 'Stacker Box Composition');
	const artist = escapeHtml(htmlMeta?.artist || '');
	const description = escapeHtml(htmlMeta?.description || '');

	let metaTags = '';
	if (artist) metaTags += `<meta name="artist" content="${artist}">\n`;
	if (description) metaTags += `<meta name="description" content="${description}">\n`;
	if (htmlMeta?.year) metaTags += `<meta name="creation-date" content="${escapeHtml(htmlMeta.year)}">\n`;
	metaTags += `<meta name="arweave-notice" content="This composition is permanently stored on the Arweave blockchain. It cannot be deleted or modified.">\n`;

	const sw = safeNumber(settings.width, CANVAS_MIN, CANVAS_MAX);
	const sh = safeNumber(settings.height, CANVAS_MIN, CANVAS_MAX);

	return `<!-- Generated by StackerBox -->
<!-- This composition is permanently stored on the Arweave blockchain and cannot be deleted or modified. -->
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
${metaTags}<style>
*, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }
html, body {
	width: 100%;
	height: 100%;
	overflow: hidden;
	background: transparent;
}
#container {
	position: absolute;
	top: 0;
	left: 0;
	width: ${sw}px;
	height: ${sh}px;
	transform-origin: 0 0;
	overflow: hidden;
}
</style>
</head>
<body>
<div id="container">
${layerElements}
</div>
<script>
// Layer loading powered by StackerBox
(function() {
	var CORE_GATEWAYS = ${coreGatewaysJson};
	var GATEWAYS = ${gatewaysJson};
	var TIMEOUT = 8000;
	var CORE_TIMEOUT = 4000;
	var PREFERRED = null;

	function shuffle(arr) {
		for (var i = arr.length - 1; i > 0; i--) {
			var j = Math.floor(Math.random() * (i + 1));
			var tmp = arr[i];
			arr[i] = arr[j];
			arr[j] = tmp;
		}
	}
	shuffle(GATEWAYS);
	GATEWAYS = CORE_GATEWAYS.concat(GATEWAYS);
	GATEWAYS = GATEWAYS.filter(function(gw, i) { return GATEWAYS.indexOf(gw) === i; });

	var c = document.getElementById('container');
	var cw = ${sw};
	var ch = ${sh};

	function fit() {
		var s = Math.min(window.innerWidth / cw, window.innerHeight / ch, 1);
		var ox = (window.innerWidth - cw * s) / 2;
		var oy = (window.innerHeight - ch * s) / 2;
		c.style.transform = 'translate(' + ox + 'px, ' + oy + 'px) scale(' + s + ')';
	}
	fit();
	window.addEventListener('resize', fit);

	function url(gateway, tx) {
		return gateway + '/' + tx;
	}

	function loadLayer(el, tx, kind, startIdx) {
		var idx = startIdx;
		var triedPreferred = false;

		function next() {
			if (PREFERRED && !triedPreferred) {
				triedPreferred = true;
				attempt(PREFERRED);
				return;
			}
			if (PREFERRED && triedPreferred) {
				PREFERRED = null;
				idx = 0;
			}
			if (idx >= GATEWAYS.length) return;
			attempt(GATEWAYS[idx]);
			idx++;
		}

		function attempt(gateway) {
			var target = url(gateway, tx);
			var isCore = CORE_GATEWAYS.indexOf(gateway) !== -1;
			if (kind === 'img') {
				tryImg(el, target, gateway, isCore);
			} else {
				tryIframe(el, target, gateway, isCore);
			}
		}

		function tryImg(el, target, gateway, isCore) {
			var done = false;
			var timer = setTimeout(function() {
				if (done) return;
				done = true;
				el.src = '';
				next();
			}, isCore ? CORE_TIMEOUT : TIMEOUT);

			function finish(success) {
				if (done) return;
				done = true;
				clearTimeout(timer);
				if (success && !PREFERRED) PREFERRED = gateway;
				if (!success) next();
			}

			el.addEventListener('load', function() { finish(true); }, { once: true });
			el.addEventListener('error', function() { finish(false); }, { once: true });
			el.src = target;
		}

		function tryIframe(el, target, gateway, isCore) {
			var done = false;
			var controller = new AbortController();
			var expectedHash = el.getAttribute('data-hash');
			var timer = setTimeout(function() {
				if (done) return;
				done = true;
				controller.abort();
				next();
			}, isCore ? CORE_TIMEOUT : TIMEOUT);

			fetch(target, { mode: 'cors', signal: controller.signal })
				.then(function(res) {
					if (!res.ok) throw new Error('Gateway request failed');
					return res.arrayBuffer();
				})
				.then(function(bytes) {
					if (done) return null;
					if (!expectedHash) return bytes;
					return crypto.subtle.digest('SHA-256', bytes).then(function(digest) {
						var actualHash = Array.from(new Uint8Array(digest)).map(function(b) {
							return b.toString(16).padStart(2, '0');
						}).join('');
						if (actualHash !== expectedHash.toLowerCase()) throw new Error('Content hash mismatch');
						return bytes;
					});
				})
				.then(function(bytes) {
					if (done || !bytes) return;
					done = true;
					clearTimeout(timer);
					el.srcdoc = new TextDecoder().decode(bytes);
					if (!PREFERRED) PREFERRED = gateway;
				})
				.catch(function() {
					if (done) return;
					done = true;
					clearTimeout(timer);
					next();
				});
		}

		next();
	}

	var elements = document.querySelectorAll('[data-tx]');
	for (var i = 0; i < elements.length; i++) {
		(function(el) {
			var tx = el.getAttribute('data-tx');
			var kind = el.getAttribute('data-kind');
			loadLayer(el, tx, kind, 0);
		})(elements[i]);
	}
})();
<\/script>
</body>
</html>`;
}

export interface SharedCompositionLayer {
	arTxId: string;
	name: string;
	type: LayerData['type'];
	x: number;
	y: number;
	width: number;
	height: number;
	opacity: number;
	order: number;
	contentHash?: string;
}

export interface SharedComposition {
	stackerbox: 1;
	name: string;
	width: number;
	height: number;
	artist: string;
	description: string;
	year: string;
	layers: SharedCompositionLayer[];
}

export function generateSharedCompositionJson({ name, settings, layers, htmlMeta }: ArweaveHtmlInput): string {
	return JSON.stringify({
		stackerbox: 1,
		name,
		width: safeNumber(settings.width, CANVAS_MIN, CANVAS_MAX),
		height: safeNumber(settings.height, CANVAS_MIN, CANVAS_MAX),
		artist: htmlMeta?.artist || '',
		description: htmlMeta?.description || '',
		year: htmlMeta?.year || '',
		layers: layers.map(({ layer, txId, contentHash }) => ({
			arTxId: txId,
			name: layer.name,
			type: layer.type,
			x: safeNumber(layer.x, -MAX_DIMENSION, MAX_DIMENSION),
			y: safeNumber(layer.y, -MAX_DIMENSION, MAX_DIMENSION),
			width: safeNumber(layer.width, CANVAS_MIN, MAX_DIMENSION),
			height: safeNumber(layer.height, CANVAS_MIN, MAX_DIMENSION),
			opacity: safeNumber(layer.opacity, 0, 100),
			order: safeNumber(layer.order, 0, 10000),
			contentHash: contentHash || undefined
		}))
	});
}

function escapeHtml(str: string): string {
	return str
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}